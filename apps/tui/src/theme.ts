function parseHexColor(hex: string): [number, number, number] | null {
  const normalized = hex.trim().replace(/^#/, "");
  if (!/^[0-9a-fA-F]{6}$/.test(normalized)) return null;
  return [
    Number.parseInt(normalized.slice(0, 2), 16),
    Number.parseInt(normalized.slice(2, 4), 16),
    Number.parseInt(normalized.slice(4, 6), 16),
  ];
}

function toHexChannel(value: number): string {
  return Math.max(0, Math.min(255, Math.round(value)))
    .toString(16)
    .padStart(2, "0");
}

function mixHexColor(color: string, target: string, targetWeight: number): string {
  const sourceRgb = parseHexColor(color);
  const targetRgb = parseHexColor(target);
  if (!sourceRgb || !targetRgb) return color;
  const sourceWeight = 1 - targetWeight;
  return `#${sourceRgb.map((channel, index) =>
    toHexChannel(channel * sourceWeight + targetRgb[index] * targetWeight),
  ).join("")}`;
}

function toneDownThemeColors(colors: ThemeColors): ThemeColors {
  const toned = { ...colors };
  for (const key of TONED_DOWN_TEXT_KEYS) {
    toned[key] = mixHexColor(colors[key], colors.muted, 0.34);
  }
  return toned;
}

